#pragma once

#include <Arduino.h>
#include "NetCommand.h"

// NetworkManager владеет подключением станции WiFi, минимальным HTTP-сервером и
// эндпойнтом WebSocket, который шлёт JSON телеметрии клиентам дашборда и принимает
// команды в текстовых кадрах (start/stop/park), которые ставятся в очередь
// FreeRTOS для рассылки из главного loop.
//
// Все методы статические; менеджер - почти-синглтон в пространстве имён с классовой
// областью видимости. begin() запускает всё, loop() должен вызываться из
// Arduino loop() (или любой задачи), чтобы прокачивать очередь команд и
// транслировать телеметрию с периодом NET_TELEMETRY_INTERVAL_MS. Входящие команды
// выводятся через onCommand(), который является слабой заглушкой, .ino (или другая
// единица трансляции) может переопределить его, чтобы реально управлять машиной
// состояний.

class NetworkManager {
 public:
  // Подключить WiFi (режим STA), используя Config::WIFI_SSID / WIFI_PASSWORD,
  // задать имя хоста, запустить AsyncWebServer (заглушка HTTP GET / + эндпойнт WS)
  // и создать очередь команд. Безопасно вызывать один раз из setup().
  static void begin();

  // Прокачать очередь команд (рассылая каждую разобранную команду в onCommand()) и
  // рассылать кадр JSON телеметрии всем подключённым клиентам WS каждые
  // NET_TELEMETRY_INTERVAL_MS. Предназначено для вызова из Arduino loop().
  static void loop();

  // Колбэк, вызываемый для каждой команды, извлечённой из очереди команд WS.
  // Реализация по умолчанию в NetworkManager.cpp - слабая заглушка, которая лишь
  // пишет в лог; переопределить (задать собственную несла́бую копию), чтобы реально
  // управлять машиной состояний.
  static void onCommand(NetCommand::Command cmd);

  // Немедленно разослать произвольный кадр JSON события всем подключённым клиентам
  // WS (переходы состояний, события парковки, события ошибок). Защищено так же, как
  // периодическая рассылка телеметрии (только когда WiFi поднят и подключён хотя бы
  // один клиент). Можно безопасно вызывать из задачи двигателя/управления, не
  // только из loop() - AsyncWebSocket::textAll в этой библиотеке безопасен для
  // задач. Держать полезную нагрузку малой; вызов неблокирующий и не должен
  // добавлять задержек.
  static void broadcastEvent(const String& json);

  // Безопасная для задач, неблокирующая рассылка события. Копирует JSON в слот
  // фиксированного размера во внутренней очереди FreeRTOS и сразу возвращается -
  // никакого textAll(), никаких выделений кучи, никакого мьютекса на стороне
  // вызывающего. loop() (на сетевой задаче) вычерпывает очередь и выполняет
  // собственно sWs.textAll(). Предназначено для вызывающих на задаче
  // двигателя/управления (ядро 1), которые не должны платить задержку мьютекса +
  // кучи у textAll. Полезные нагрузки длиннее слота усекаются; события
  // доставляются по возможности и молча отбрасываются, когда очередь полна.
  static void queueEvent(const char* json);

  // ── Геттеры состояния ────────────────────────────────────────────────────────
  // Аксессоры только для чтения, чтобы вызывающие (например, строка [DIAG] в
  // Serial) могли сообщать о связности, не обращаясь напрямую к WiFi или серверу WS.

  // True, когда связь STA ассоциирована и имеет IP (WiFi.status()==WL_CONNECTED).
  static bool isWifiConnected();

  // Число текущих подключённых клиентов WebSocket.
  static uint8_t wsClientCount();

  // IP STA в виде четырёх октетов через точку, или "0.0.0.0", когда WiFi не
  // подключён.
  static String wifiIp();
};
