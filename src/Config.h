// ПРЕДПОЧТИТЕЛЬНЫЙ путь к предсказуемому адресу: MAC STA у ESP32 стабилен (берётся
// из заводского eFuse), поэтому нужно зарезервировать IP для этого MAC в настройках
// DHCP точки доступа/роутера. MAC печатается один раз при загрузке (см. NetworkManager::begin)
// как "[NET] STA MAC xx:xx:...". Это работает в любой сети, включая корпоративный
// WiFi, без жёсткого задания адреса.
//
// Статический IP ниже - НЕОБЯЗАТЕЛЬНЫЙ запасной вариант для сетей, где нельзя
// сделать DHCP-резервирование (например, телефонная точка доступа, которая ещё и
// блокирует mDNS). По умолчанию ОТКЛЮЧЁН, потому что жёстко заданный адрес, уже
// занятый в LAN, вызывает тихий конфликт. Включать только когда известны подсеть
// и то, что адрес свободен. При включении WiFi.config() применяется перед
// WiFi.begin(); если значения некорректны, код пишет предупреждение и откатывается
// на DHCP.
constexpr bool NET_USE_STATIC_IP = false;             // держать false -> DHCP (резервировать по MAC)
constexpr const char* NET_STATIC_IP = "192.168.1.50"; // используется только если NET_USE_STATIC_IP
