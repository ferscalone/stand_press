// ── Операторское ПЕРЕТАРИРОВАНИЕ (перезахват нуля тензодатчика) ───────────────
// Ноль HX711 дрейфует (по наблюдениям на стенде: в домашней позиции без
// нагрузки raw~114530 против зашитого HX711_OFFSET=122800 -> смещение ~25 г).
// FACTOR (наклон) остаётся верным; движется только смещение нуля. Решение -
// операторское ПЕРЕТАРИРОВАНИЕ в логическом нуле: захватить текущее устоявшееся
// raw как новое смещение и сохранить его. Это НЕ непрерывный фильтр дрейфа - во
// время HOLD_LOAD медленное изменение показания есть ИЗМЕРЕНИЕ зажатого объекта и
// никогда не должно обнуляться. Поэтому перетарирование - дискретное, защищённое
