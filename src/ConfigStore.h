#pragma once

#include <Arduino.h>

#include "Config.h"

// Единый согласованный набор из трёх значений конфигурации управления нагрузкой (кг).
// Отражает оперативное gConfig в .ino; используется загрузкой/сохранением ConfigStore
// и валидатором /v1/config.
//
// Смещение нуля HX711 `offset` (в сырых отсчётах) хранится в ТОМ ЖЕ сохраняемом blob,
// но представляет ОТДЕЛЬНУЮ сущность относительно тройки кг: оно задаётся операторским
// перетарированием, а не через /v1/config. Оно переносится здесь (а не в параллельном
// API ConfigStore), чтобы сохраняемый blob оставался единой структурой / одним
// nvs_commit, а существующие вызовы /v1/config не затрагивались - они просто продолжают
// заполнять target/min/max, а load()/save() попутно сохраняют и восстанавливают offset.
// validateConfig() НЕ проверяет offset (это не значение окна кг); корректность offset
// проверяется отдельно в load() по диапазону HX711_OFFSET_MIN..MAX.
struct ConfigTriple {
  float targetKg;
  float minKg;
  float maxKg;
  // Оперативное смещение нуля HX711 (в сырых отсчётах). ВНИМАНИЕ: намеренно НЕ имеет
  // внутриклассового инициализатора по умолчанию - иначе ConfigTriple перестал бы быть
  // агрегатом в рамках C++11, под который компилирует инструментарий Arduino-ESP32, что
  // сломало бы множество мест агрегатной инициализации через скобки (например,
  // `ConfigTriple{a,b,c}` в /v1/config и у вызывающих getConfigSnapshot). Без
  // инициализатора структура остаётся агрегатом: инициализация тремя полями через скобки
  // выполняет value-initialization offset в 0.0f, поэтому КАЖДЫЙ вызывающий, которому
  // важен offset, ОБЯЗАН задать его явно (значения по умолчанию в setup() передают все
  // четыре; /v1/config и tryRetare присваивают .offset перед save()). ConfigStore::load()
  // всегда записывает out.offset (из blob или из переданного значения по умолчанию), так
  // что загруженная тройка всегда полностью заполнена.
  float offset;
};

// Проверяет тройку конфигурации. Возвращает nullptr при корректных значениях, иначе
// короткую статическую строку-причину, пригодную для "detail" ответа 400. Правила
// (только относительные + ноль; БЕЗ жёсткого верхнего предела - механическая стенка на
// этом стенде не фиксирована):
//   * без NaN
//   * minKg >= 0
//   * minKg < maxKg
//   * minKg <= targetKg <= maxKg
const char* validateConfig(float targetKg, float minKg, float maxKg);

namespace ConfigStore {

// Загружает сохранённую конфигурацию в out. Для любого ключа, отсутствующего в NVS,
// заполняет соответствующее поле из `defaults`. Если полностью собранная тройка не
// проходит validateConfig (повреждённый/неполный NVS), out перезаписывается значениями
// `defaults` и возвращается false. Возвращает true только когда прочитана корректная,
// полностью сохранённая тройка.
//
// Совместимость по offset: СТАРЫЙ blob (3 float, без offset) оставляет out.offset равным
// значению `defaults`.offset (offset отсутствует -> вызывающий использует значение по
// умолчанию); НОВЫЙ blob (4 float) авторитетен и для offset, ЕСЛИ ТОЛЬКО сохранённый
// offset не проваливает проверку диапазона HX711_OFFSET_MIN..MAX, в этом случае к
// `defaults`.offset откатывается только offset (тройка кг НЕ отвергается из-за одного лишь
// некорректного offset). Возвращаемое bool отражает только сохранность тройки кг;
// сравните out.offset со своим значением по умолчанию, если нужно узнать, присутствовал
// ли сохранённый offset.
bool load(ConfigTriple& out, const ConfigTriple& defaults);

// Сохраняет все значения (target/min/max И offset) как единый blob (по мере
// возможности; при неудаче пишет в лог). Вызывать только после того, как validateConfig
// прошла для тройки кг.
void save(const ConfigTriple& cfg);

// Домашний угол (логический ноль, абсолютные градусы AS5600), заданный калибровкой
// нуля кулачков. Хранится ОТДЕЛЬНЫМ ключом NVS, а не в общем blob: так существующие
// вызовы save() (config/tare) не могут затереть его устаревшим значением.
// loadHomeAngle возвращает сохранённый угол или `fallback`, если ключа нет либо
// значение вне [0, 360).
float loadHomeAngle(float fallback);
void saveHomeAngle(float homeAngleDeg);

}  // namespace ConfigStore
