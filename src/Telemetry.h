#pragma once

#include <Arduino.h>
#include "SystemState.h"

// Единый согласованный снимок каждого поля телеметрии, которое отображает панель. .ino
// заполняет его в одной секции portENTER_CRITICAL/portEXIT_CRITICAL, так что все поля
// берутся из одного и того же момента (без рваного чтения через отдельные блокируемые
// геттеры). buildTelemetryJson() формирует вывод из локальной копии этой структуры.
struct TelemetrySnapshot {
  SystemState state;
  float loadKg;
  long loadRaw;
  bool loadReady;
  float encAbsDeg;
  float encRelDeg;
  bool encoderFault;
  float targetKg;
  float rangeMinKg;
  float rangeMaxKg;
  // Текущее оперативное смещение нуля HX711 (сырые отсчёты) - перетарируемый ноль, а не
  // значение по умолчанию из Config.h. Сообщается, чтобы панель могла показать/проверить
  // текущий ноль.
  long loadOffset;
  // True, когда защита перетарирования в данный момент удовлетворена (IDLE && вал в
  // пределах RETARE_MAX_REL_DEG от домашней позиции && нагрузка готова && |нагрузка| <=
  // RETARE_MAX_ABS_KG), то есть /v1/tare прямо сейчас был бы принят. Позволяет панели
  // включать/выключать кнопку тарирования без дублирования логики защиты.
  bool tareOk;
  // Действующий домашний угол (абс. градусы AS5600) - логический ноль, задаваемый
  // калибровкой нуля кулачков. Заодно служит дашборду признаком того, что прошивка
  // поддерживает калибровку.
  float homeAbsDeg;
};

// Атомарный доступ: копирует все поля телеметрии из разделяемого состояния под одной
// критической секцией. Определён в .ino (где размещена структура SharedData).
void getTelemetrySnapshot(TelemetrySnapshot& out);

// Формирует JSON-снимок телеметрии из текущего глобального состояния нагрузочного
// стенда. Строка собирается во внутренний статический буфер и возвращается по ссылке;
// вызывающий должен скопировать или отправить её до следующего вызова.
//
// Замечание о соответствии полей: это МЕХАНИЧЕСКИЙ нагрузочный стенд, измеряющий силу
// (кг) тензодатчиком HX711, а не электронная нагрузка, измеряющая ток/напряжение. В
// прошивке нет измерения тока/напряжения/мощности. Поэтому телеметрия сообщает реальные
// величины: load_kg (измеренная нагрузка) и target_kg (заданный центр целевого окна).
// Имена current_ma / voltage_mv / power_mw из исходного задания не соответствуют ни
// одному реальному сигналу здесь и намеренно опущены, а не сфабрикованы.
//
// Отдаваемые поля:
//   state          - текущее SystemState строкой ("IDLE", "SEEK_LOAD", ...)
//   load_kg        - последняя отфильтрованная нагрузка в килограммах
//   target_kg      - заданный центр целевого окна нагрузки (кг); теперь ОПЕРАТИВНОЕ
//                    значение (gConfig), задаётся через POST /v1/config, не constexpr
//   range_min_kg   - заданный минимум допустимого окна нагрузки (кг), оперативный
//   range_max_kg   - заданный максимум допустимого окна нагрузки (кг), оперативный
//   load_raw       - последний мгновенный сырой отсчёт HX711
//   load_ready     - 1, если тензодатчик выдал корректный отсчёт
//   uptime_ms      - millis() с момента запуска
//   encoder_abs_deg - абсолютный угол энкодера (град)
//   encoder_rel_deg - относительный (от домашней позиции) угол энкодера (град)
//   encoder_fault  - 1, если установлена ошибка/сбой позиции энкодера
//   load_offset    - текущее оперативное смещение нуля HX711 (сырые отсчёты), перетарируемое
//   tare_ok        - 1, если перетарирование сейчас было бы принято (защита удовлетворена)
//   home_abs_deg   - действующий домашний угол (логический ноль), абс. градусы
String buildTelemetryJson();

// Формирует компактный JSON-кадр дискретного события для потока WS, например
//   {"event":"state","detail":"SEEK_LOAD","uptime_ms":12345}
// Используется для мгновенной отправки переходов состояний, событий парковки и событий
// ошибок клиентам панели в момент их возникновения, а не в ожидании следующего
// периодического тика телеметрии. `event` - короткий токен типа ("state"/"park"/"error"),
// а `detail` - короткая заведомо безопасная нагрузка (имя состояния, строка нагрузки или
// причина ошибки). Ни то, ни другое не экранируется - вызывающие передают только
// фиксированные короткие токены.
String buildEventJson(const char* event, const char* detail);
